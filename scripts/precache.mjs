// Writes the list of app files into sw.js so the service worker can cache them,
// and the preload tags for the scripts and data files into index.html.
// Run after adding or removing files: node scripts/precache.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, posix, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DIRS = ['src', 'data', 'content', 'icons'];
const FILES = ['./', 'index.html', 'manifest.webmanifest'];
const ENTRY = 'src/main.js';

/** @param {string} dir @returns {string[]} */
export function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

export function precacheList() {
  const files = DIRS.flatMap((d) => walk(join(ROOT, d)))
    .map((p) => relative(ROOT, p).split('\\').join('/'))
    .filter((p) => !p.endsWith('.DS_Store') && !p.endsWith('.map') && !p.endsWith('SOURCE.md'))
    .sort();
  return [...FILES, ...files];
}

export function render(list) {
  return `// PRECACHE:START (generated by scripts/precache.mjs)\nconst PRECACHE = ${JSON.stringify(list, null, 2)};\n// PRECACHE:END`;
}

/**
 * The relative modules a source file imports or re-exports. Handles imports
 * that span lines and either kind of quote; type-only import('…') in comments
 * is not at the start of a line, so it is left out.
 * @param {string} src
 * @returns {string[]}
 */
export function importSpecifiers(src) {
  return [...src.matchAll(/^[ \t]*(?:import|export)\b(?:[^'";]*?\bfrom)?\s*(['"])([^'"\n]+)\1/gm)]
    .map((m) => m[2])
    .filter((spec) => spec.startsWith('.'));
}

/**
 * The data files a source file names, in single, double or template quotes.
 * @param {string} src
 * @returns {string[]}
 */
export function dataFiles(src) {
  return [...src.matchAll(/(['"`])(data\/[\w./-]+)\1/g)].map((m) => m[2]);
}

/**
 * Every module the entry script loads, found by reading the imports.
 * The entry itself is left out: the page's script tag already fetches it.
 * @returns {string[]}
 */
export function moduleList() {
  const seen = new Set([ENTRY]);
  const queue = [ENTRY];
  for (const file of queue) {
    const src = readFileSync(join(ROOT, file), 'utf8');
    for (const spec of importSpecifiers(src)) {
      const dep = posix.join(posix.dirname(file), spec);
      if (!seen.has(dep)) {
        seen.add(dep);
        queue.push(dep);
      }
    }
  }
  seen.delete(ENTRY);
  return [...seen].sort();
}

/** The data files the app fetches by name, found in the source of the modules. */
export function dataList() {
  const files = [ENTRY, ...moduleList()].flatMap((f) => dataFiles(readFileSync(join(ROOT, f), 'utf8')));
  return [...new Set(files)].sort();
}

export function renderPreload() {
  const tags = [
    ...moduleList().map((f) => `<link rel="modulepreload" href="${f}">`),
    ...dataList().map((f) => `<link rel="preload" href="${f}" as="fetch" crossorigin>`),
  ];
  return `<!-- PRELOAD:START (generated by scripts/precache.mjs) -->\n  ${tags.join('\n  ')}\n  <!-- PRELOAD:END -->`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sw = join(ROOT, 'sw.js');
  const src = readFileSync(sw, 'utf8');
  const out = src.replace(/\/\/ PRECACHE:START[\s\S]*?\/\/ PRECACHE:END/, render(precacheList()));
  writeFileSync(sw, out);
  const page = join(ROOT, 'index.html');
  writeFileSync(page, readFileSync(page, 'utf8').replace(/<!-- PRELOAD:START[\s\S]*?<!-- PRELOAD:END -->/, renderPreload()));
  console.log(`sw.js: ${precacheList().length} files, index.html: ${moduleList().length + dataList().length} preloads`);
}
